export function hasFormLayoutComponent(
  layoutKey
) {
  const key = String(
    layoutKey || ""
  ).trim();

  return Object.prototype.hasOwnProperty.call(
    FORM_LAYOUT_COMPONENTS,
    key
  );
}

export function resolveFormLayoutComponent(
  layoutKey
) {
  return (
    FORM_LAYOUT_COMPONENTS[layoutKey] ||
    DefaultFormLayout
  );
}